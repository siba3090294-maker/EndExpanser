/* =========================
   TRANSLATION
========================= */

const TRANSLATE_API =
  "https://api.mymemory.translated.net/get"

const translationMemory = new Map()

function langPair(lang) {
  return lang === "ru"
    ? "en|ru"
    : lang === "uk"
    ? "en|uk"
    : null
}

function translationCacheKey(lang, text) {
  return `endexpanser-tr:${lang}:${text}`
}

function readTranslationCache(lang, text) {
  const k = translationCacheKey(lang, text)

  if (translationMemory.has(k))
    return translationMemory.get(k)

  try {
    const v = localStorage.getItem(k)

    if (v) {
      translationMemory.set(k, v)
      return v
    }
  } catch (_) {}

  return null
}

function writeTranslationCache(lang, text, value) {
  const k = translationCacheKey(lang, text)

  translationMemory.set(k, value)

  try {
    if (text.length < 900)
      localStorage.setItem(k, value)
  } catch (_) {}
}

function splitForTranslation(text, max = 430) {
  text = String(text || "").trim()

  if (text.length <= max)
    return text ? [text] : []

  const parts = []
  let rest = text

  while (rest.length > max) {
    let cut = Math.max(
      rest.lastIndexOf(". ", max),
      rest.lastIndexOf("! ", max),
      rest.lastIndexOf("? ", max),
      rest.lastIndexOf(", ", max),
      rest.lastIndexOf(" ", max)
    )

    if (cut < max * 0.45)
      cut = max

    parts.push(
      rest.slice(0, cut + 1).trim()
    )

    rest =
      rest.slice(cut + 1).trim()
  }

  if (rest)
    parts.push(rest)

  return parts
}

async function translateChunk(text, lang) {
  if (!text || lang === "en")
    return text

  const cached =
    readTranslationCache(lang, text)

  if (cached)
    return cached

  const pair = langPair(lang)

  if (!pair)
    return text

  try {
    const u =
      `${TRANSLATE_API}?q=${encodeURIComponent(text)}` +
      `&langpair=${encodeURIComponent(pair)}`

    const r = await fetch(u)

    if (!r.ok)
      throw new Error(`translate ${r.status}`)

    const j = await r.json()

    const out =
      j?.responseData?.translatedText ||
      text

    writeTranslationCache(
      lang,
      text,
      out
    )

    return out
  } catch (e) {
    console.warn(
      "translation unavailable",
      e
    )

    return text
  }
}

async function translateText(
  text,
  lang = projectLang
) {
  if (!text || lang === "en")
    return text

  const chunks =
    splitForTranslation(text)

  const out = []

  for (const c of chunks)
    out.push(
      await translateChunk(c, lang)
    )

  return out.join(" ")
}

function stripBuiltInLocales(md = "") {
  return String(md)
    .split(
      /^##\s+(Русский|Українська|Ukrainian|Russian)\s*$/mi
    )[0]
    .trim()
}

async function translateMarkdown(
  md,
  lang = projectLang
) {
  const source =
    stripBuiltInLocales(md)

  if (lang === "en")
    return source

  const lines =
    source
      .replace(/\r/g, "")
      .split("\n")

  const out = []

  let inCode = false

  for (const line of lines) {
    if (/^```/.test(line.trim())) {
      inCode = !inCode
      out.push(line)
      continue
    }

    if (
      inCode ||
      !line.trim() ||
      /^![^]*\]/.test(line.trim())
    ) {
      out.push(line)
      continue
    }

    const m = line.match(
      /^(\s*(?:#{1,6}\s+|[-*+]\s+|\d+\.\s+|>\s+)?)(.*)$/
    )

    const prefix =
      m ? m[1] : ""

    const body =
      m ? m[2] : line

    if (!body.trim()) {
      out.push(line)
      continue
    }

    out.push(
      prefix +
      await translateText(
        body,
        lang
      )
    )
  }

  return out.join("\n")
}

/* =========================
   MARKDOWN
========================= */

function basicMarkdown(md = "") {
  let s =
    escapeHtml(md)
      .replace(/\r/g, "")

  s = s
    .replace(
      /^### (.+)$/gm,
      "<h3>$1</h3>"
    )
    .replace(
      /^## (.+)$/gm,
      "<h2>$1</h2>"
    )
    .replace(
      /^# (.+)$/gm,
      "<h1>$1</h1>"
    )
    .replace(
      /\*\*(.+?)\*\*/g,
      "<strong>$1</strong>"
    )
    .replace(
      /\*(.+?)\*/g,
      "<em>$1</em>"
    )
    .replace(
      /`([^`]+)`/g,
      "<code>$1</code>"
    )
    .replace(
      /\[([^]+)\](https?:\/\/[^)]+)/g,
      '<a href="$2" target="_blank" rel="noreferrer">$1</a>'
    )

  const lines =
    s.split("\n")

  let out = []
  let inUl = false
  let inOl = false

  for (const line of lines) {
    if (/^[-*] /.test(line)) {
      if (!inUl) {
        out.push("<ul>")
        inUl = true
      }

      out.push(
        "<li>" +
        line.replace(
          /^[-*] /,
          ""
        ) +
        "</li>"
      )

      continue
    }

    if (/^\d+\. /.test(line)) {
      if (!inOl) {
        out.push("<ol>")
        inOl = true
      }

      out.push(
        "<li>" +
        line.replace(
          /^\d+\. /,
          ""
        ) +
        "</li>"
      )

      continue
    }

    if (inUl) {
      out.push("</ul>")
      inUl = false
    }

    if (inOl) {
      out.push("</ol>")
      inOl = false
    }

    if (!line.trim())
      continue

    if (/^<h[123]>/.test(line))
      out.push(line)
    else if (/^&gt; /.test(line))
      out.push(
        "<blockquote>" +
        line.replace(
          /^&gt; /,
          ""
        ) +
        "</blockquote>"
      )
    else
      out.push(
        "<p>" +
        line +
        "</p>"
      )
  }

  if (inUl)
    out.push("</ul>")

  if (inOl)
    out.push("</ol>")

  return out.join("")
}

