function applyProjectLanguage(lang) {
  projectLang =
    ["en", "ru", "uk"].includes(lang)
      ? lang
      : "en"

  localStorage.setItem(
    "endexpanser-lang",
    projectLang
  )

  document.documentElement.lang =
    projectLang

  document
    .querySelectorAll(
      "[data-i18n]"
    )
    .forEach(el => {
      el.innerHTML =
        pt(el.dataset.i18n)
    })

  document
    .querySelectorAll(
      "[data-lang-switcher]"
    )
    .forEach(sw => {
      const current =
        sw.querySelector(
          ".lang-current"
        )

      if (
        current &&
        current.childNodes[0]
      ) {
        current.childNodes[0].nodeValue =
          projectLang.toUpperCase() +
          " "
      }

      sw
        .querySelectorAll(
          "[data-lang]"
        )
        .forEach(b =>
          b.classList.toggle(
            "active",
            b.dataset.lang ===
              projectLang
          )
        )
    })

  if (window.__projectData)
    renderProject(
      window.__projectData
    )
}

function initProjectLanguage() {
  document
    .querySelectorAll(
      "[data-lang-switcher]"
    )
    .forEach(sw => {
      const btn =
        sw.querySelector(
          ".lang-current"
        )

      if (btn) {
        btn.addEventListener(
          "click",
          e => {
            e.stopPropagation()

            const open =
              sw.classList.toggle(
                "open"
              )

            btn.setAttribute(
              "aria-expanded",
              open
            )
          }
        )
      }

      sw
        .querySelectorAll(
          "[data-lang]"
        )
        .forEach(b =>
          b.addEventListener(
            "click",
            () => {
              applyProjectLanguage(
                b.dataset.lang
              )

              sw.classList.remove(
                "open"
              )
            }
          )
        )
    })

  addEventListener(
    "click",
    () =>
      document
        .querySelectorAll(
          ".language-switcher.open"
        )
        .forEach(sw =>
          sw.classList.remove(
            "open"
          )
        )
  )

  applyProjectLanguage(
    projectLang
  )
}

