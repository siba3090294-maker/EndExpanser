function initReveal() {
  const io =
    new IntersectionObserver(
      entries =>
        entries.forEach(e => {
          if (e.isIntersecting) {
            e.target.classList.add(
              "visible"
            )

            io.unobserve(
              e.target
            )
          }
        }),
      {
        threshold: 0.1
      }
    )

  document
    .querySelectorAll(
      ".reveal:not(.visible)"
    )
    .forEach(
      el => io.observe(el)
    )
}

initReveal()

